"""Generate the AC brand table for components/irac from a pinned IRremoteESP8266.

Usage: python tools/gen_ac_table.py <IRremoteESP8266 dir> <components/irac dir>

brand -> protocol comes from the library itself: IRac::sendAc's `case TYPE: IRClass ac(`
gives type -> class, the class's ir_<File>.h gives the file, SupportedProtocols.md lists
the brands per file. Writes ac_brands.inc and send_flags.cmake (only the SEND_* macros
IRac.cpp uses, so non-AC protocols stay out of the firmware).
"""
import collections, glob, os, re, sys

lib, out = sys.argv[1], sys.argv[2]
src = os.path.join(lib, "src")
ac = open(os.path.join(src, "IRac.cpp"), encoding="utf-8").read()
body = ac[ac.index("bool IRac::sendAc(const stdAc::state_t desired"):]
body = body[: body.index("\n}\n")]
cases = re.findall(
    r"case\s+(?:decode_type_t::)?([A-Z0-9_]+)\s*:\s*\{?\s*(?:#if[^\n]*\n)?\s*(IR[A-Za-z0-9]+)\s+ac\(",
    body)
assert len(cases) > 40, f"only {len(cases)} AC protocols found - IRac.cpp layout changed?"

cls2file = {}
for h in glob.glob(os.path.join(src, "ir_*.h")):
    for c in re.findall(r"^class\s+(IR\w+)\s*\{", open(h, encoding="utf-8").read(), re.M):
        cls2file[c] = os.path.basename(h)[3:-2]

file2brands = collections.defaultdict(set)
for line in open(os.path.join(lib, "SupportedProtocols.md"), encoding="utf-8"):
    if not line.startswith("| ["):
        continue
    cols = [x.strip() for x in line.strip().strip("|").split("|")]
    proto = re.sub(r"\[([^\]]+)\].*", r"\1", cols[0])
    brand = re.sub(r"\*\*\[?([^\]\*]+).*", r"\1", cols[1]).strip()
    file2brands[proto].add(brand)

pairs = set()
for typ, cls in cases:
    brands = file2brands.get(cls2file.get(cls, ""), set())
    if not brands:  # class lives in another header: brand = first word of the type
        brands = {typ.split("_")[0].capitalize()}
    for b in brands:
        pairs.add((b, typ))

per_brand = collections.Counter(b for b, _ in pairs)
rows = sorted(pairs, key=lambda p: (p[0].lower(), p[1]))
with open(os.path.join(out, "ac_brands.inc"), "w", newline="\n") as f:
    f.write("// generated by tools/gen_ac_table.py - do not edit\n")
    for brand, typ in rows:
        label = brand if per_brand[brand] == 1 else f"{brand} ({typ})"
        label = label.replace("\\", "/").replace('"', "'")
        f.write(f'    {{"{label}", decode_type_t::{typ}}},\n')

# SEND_* used by IRac.cpp plus those inside each AC class's own source (e.g. Coolix's
# send() calls sendCoolix48, guarded by SEND_COOLIX48 which IRac.cpp never mentions)
ac_srcs = [ac] + [open(os.path.join(src, f"ir_{cls2file[c]}.cpp"), encoding="utf-8").read()
                  for _, c in cases
                  if c in cls2file and os.path.exists(os.path.join(src, f"ir_{cls2file[c]}.cpp"))]
flags = sorted({f for text in ac_srcs for f in re.findall(r"#if\s+(SEND_[A-Z0-9_]+)", text)})
with open(os.path.join(out, "send_flags.cmake"), "w", newline="\n") as f:
    f.write("# generated by tools/gen_ac_table.py - do not edit\n")
    f.write("target_compile_definitions(${COMPONENT_LIB} PRIVATE\n")
    for fl in flags:
        f.write(f"    {fl}=true\n")
    f.write(")\n")

print(f"{len(cases)} AC protocols, {len(per_brand)} brands, {len(rows)} menu entries, "
      f"{len(flags)} SEND_ flags")
